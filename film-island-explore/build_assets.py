"""Build dependency-free, ordered browser bundles for the exploration edition."""
from pathlib import Path
import hashlib,re
root=Path(__file__).resolve().parent
scripts=['data.js','missions.js','media.js','music.js','scene.js','info.js','experience.js','app.js','responsive.js']
styles=['style.css','play.css','festival.css','responsive.css','playful.css']
for output,files,separator in [('game.js',scripts,'\n;\n'),('game.css',styles,'\n')]:
 text='/* Generated by build_assets.py; edit source files and rebuild. */\n'+separator.join('/* '+name+' */\n'+(root/name).read_text() for name in files)
 (root/output).write_text(text)
html=(root/'index.html').read_text()
html=re.sub(r'<link rel="stylesheet" href="[^\"]+">','',html)
css_hash=hashlib.sha256((root/'game.css').read_bytes()).hexdigest()[:12]
html=html.replace('</head>',f'<link rel="stylesheet" href="game.css?v={css_hash}"></head>')
html=re.sub(r'<script[^>]*src="(?:'+ '|'.join(re.escape(x) for x in scripts+['game.js']) +r')(?:\?[^\"]*)?"[^>]*></script>','',html)
html=html.replace('<script src="vendor/three.min.js">','<script defer src="vendor/three.min.js">').replace('<script src="vendor/OrbitControls.js">','<script defer src="vendor/OrbitControls.js">')
js_hash=hashlib.sha256((root/'game.js').read_bytes()).hexdigest()[:12]
html=html.replace('</body>',f'<script defer src="game.js?v={js_hash}"></script></body>')
(root/'index.html').write_text(html)
print('Built ordered JS/CSS bundles; vendor license files retained separately.')
